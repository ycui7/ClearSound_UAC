#!/usr/bin/env python3
"""Generate the fixed-point tables csd_gen compiles.

Offline double-precision derivation so the firmware carries no transcendental
and no per-frame float: XS3 has no FPU, so a float op is a soft-float call, and
these are used inside the per-frame audio hook.

TABLES

  sine_q31[1024]        One cycle, int32 full scale. Linear interpolation
                        between neighbours leaves a peak error of about
                        (pi^2/8)/N^2 = 1.2e-6 (-118 dB), below the 24-bit DAC
                        path it feeds. A coarser table would put the
                        generator's own distortion above the thing being
                        measured, which defeats the purpose of a test source.

  exp2_mant[256]        2^x on x in [0,1), Q29. The log sweep evaluates its
                        closed form as 2^(ea + eb*u), so this is the one
                        transcendental on the per-frame path. Linear
                        interpolation error is ~1e-6 absolute (9e-7 relative),
                        four orders below the sweep end-frequency tolerance
                        the host gate asserts.

  log2_tab[256]         log2(1+y) on y in [0,1), Q29. Needed once per arm to
                        turn (f_start, f_stop) into the two exponents above.
                        Generated from the same expression as exp2_mant so the
                        pair cannot drift apart by hand-editing.

REMOVED: the order-2 polyBLEP tables an earlier revision emitted. The residual
measured WORSE than applying no correction at all (folded 3rd harmonic -4 dB
versus -9 dB naive; even harmonics -20 dB where a square has none), so the
square is now an odd-harmonic sum of pure NCO sines and cannot alias by
construction. Regenerating them here would put 4 KB of unread flash into the
image and invite someone to re-enable a correction that is known wrong.
"""
import math
import sys

SINE_N = 1024
SQ_HARMONICS = 32
GIBBS_SHIFT = 30             # see the table comment: normaliser is >= 1.0

EXP_N = 256                  # intervals; the tables hold EXP_N + 1 nodes
Q29 = 1 << 29                # not (2^31-1)>>2: that is one short of 1.0 and
                             # truncates 1 Hz to 0.996 Hz in the final shift
FULL = 0x7FFFFFFF


def emit_table(out, name, size_macro, vals, comment):
    out.append(comment)
    out.append("static const int32_t %s[%s] = {\n" % (name, size_macro))
    for i in range(0, len(vals), 8):
        out.append("    " + ", ".join(str(v) for v in vals[i:i + 8]) + ",\n")
    out.append("};\n\n")


def check_core_agreement(core_path):
    """The square's harmonic count is defined in TWO places: here (it sizes the
    Gibbs table) and in csd_gen_core.h (it bounds the oscillator loop). Both
    must agree, or the loop indexes past the normalisation table -- which is
    not a wrong waveform, it is an out-of-bounds read. Asserted here rather
    than left to a comment saying 'must match', because comments do not fail
    builds and this session has already been bitten twice by a constant and
    the code that reads it drifting apart.
    """
    import re
    try:
        src = open(core_path).read()
    except IOError:
        return "cannot read %s" % core_path
    m = re.search(r"#define\s+CSD_GEN_SQ_HARMONICS\s+(\d+)", src)
    if not m:
        return "CSD_GEN_SQ_HARMONICS not found in %s" % core_path
    if int(m.group(1)) != SQ_HARMONICS:
        # The constant's NAME belongs in the message, not just the path: a
        # refusal that only quotes a file and two numbers is indistinguishable
        # from other refusals (a missing core reads similarly), and the guards
        # require the reason to be verifiable, not merely present.
        return ("CSD_GEN_SQ_HARMONICS disagrees: %s says %s, "
                "this generator says %d"
                % (core_path, m.group(1), SQ_HARMONICS))
    return None


def main():
    path = sys.argv[1] if len(sys.argv) > 1 else \
        "src/extensions/csd_gen_tables.h"

    # Resolve the core header next to the output so the check works from the
    # app root (the normal cwd) and from tools/dsp.
    import os
    here = os.path.dirname(os.path.abspath(path))
    core = os.path.join(here, "csd_gen_core.h")
    if not os.path.exists(core):
        core = "src/extensions/csd_gen_core.h"
    bad = check_core_agreement(core)
    if bad:
        sys.stderr.write("TABLE GENERATOR REFUSED: %s\n" % bad)
        return 1

    out = ["// GENERATED by tools/dsp/gen_gen_tables.py -- do not edit.\n"
           "// After changing a table shape, regenerate and run the host gate:\n"
           "// tools/dsp/test_gen.cpp asserts the waveforms built from these\n"
           "// tables, so an error here fails a test rather than a measurement.\n"
           "#ifndef __csd_gen_tables_h__\n"
           "#define __csd_gen_tables_h__\n"
           "#include <stdint.h>\n\n"
           "#define CSD_GEN_SINE_N   %d\n"
           "#define CSD_GEN_EXP_N    %d\n"
           "#define CSD_GEN_EXP_N1   %d   /* nodes = intervals + 1, inclusive */\n"
           "#define CSD_GEN_SQ_HARMONICS %d\n\n"
           % (SINE_N, EXP_N, EXP_N + 1, SQ_HARMONICS)]

    sine = [int(round(FULL * math.sin(2 * math.pi * i / SINE_N)))
            for i in range(SINE_N)]
    emit_table(out, "csd_gen_sine_q31", "CSD_GEN_SINE_N", sine,
               "/* One full cycle, int32 full scale. Index = phase >> 22, so the\n"
               " * 22 low bits are the interpolation fraction. Peak at N/4. */\n")

    # N+1 nodes, i.e. [0,1] INCLUSIVE. This is load-bearing, not tidiness:
    # with N nodes the last interval interpolates entry N-1 against entry 0,
    # which wraps y->1 back to y->0. Measured consequence: a log sweep whose
    # endpoint fraction landed near 1 (4093 Hz: log2 frac 0.9995) came out at
    # 2654 Hz -- a 35% error -- while exact powers of two were perfect, so
    # spot-checking round numbers would have hidden it completely.
    exp_tab = [int(round((2.0 ** (i / EXP_N)) * Q29)) for i in range(EXP_N + 1)]
    emit_table(out, "csd_gen_exp2_mant", "CSD_GEN_EXP_N1", exp_tab,
               "/* 2^(i/%d) in Q29, i in [0,%d]. Entry %d is exactly 2.0: the\n"
               " * range is inclusive so the final interpolation step does not\n"
               " * wrap to entry 0. Consumers index [i] and [i+1] with no mask.\n"
               " * Scaled by the caller as (mant << ip + 2^28) >> 29 -- rounding\n"
               " * matters: truncating here cost ~0.004 Hz at the 1 Hz end. */\n"
               % (EXP_N, EXP_N, EXP_N))

    log_tab = [int(round(math.log2(1.0 + i / EXP_N) * Q29))
               for i in range(EXP_N + 1)]
    emit_table(out, "csd_gen_log2_tab", "CSD_GEN_EXP_N1", log_tab,
               "/* log2(1 + i/%d) in Q29, inclusive range, entry %d is exactly\n"
               " * 1.0. Same node placement as the table above so the pair\n"
               " * cannot disagree by hand-editing. */\n"
               % (EXP_N, EXP_N))

    # Gibbs normalisation, one entry per harmonic count actually used.
    #
    # A band-limited square is sum_{k<N} sin(2*pi*(2k+1)*t)/(2k+1), and that
    # partial sum peaks ABOVE the ideal +-1 -- the Gibbs overshoot -- by an
    # amount that depends on N: 1.00000 at N=1 (just the fundamental),
    # 0.94281 at N=2, 0.92603 at N=32. The number of terms that fit below
    # Nyquist depends on the requested frequency, so a single normalisation
    # constant is wrong for every frequency except the one it was measured
    # at: dividing by the N=32 peak makes a 24-term square (1 kHz at 48 kHz)
    # exceed the requested amplitude by ~0.04%, which the host gate caught.
    # Tabulating 1/peak(N) makes `amp` mean the delivered peak at every
    # frequency, which is what the descriptor promises.
    # Incremental: S_N(t) = S_{N-1}(t) + sin(2*pi*(2N-1)*t)/(2N-1), so one
    # pass of M sines per N rather than N -- O(M*N) instead of O(M*N^2).
    # The same accumulator also bounds the peak correctly: the maximum of the
    # partial sum over t in [0,1) is what normalisation must divide by.
    M = 262144                       # power of two: exact 1/M arithmetic
    acc = [0.0] * M
    peaks = []
    for k in range(SQ_HARMONICS):
        h = 2 * k + 1
        w = 2.0 * math.pi * h / M
        inv = 1.0 / h
        pk = 0.0
        for i in range(M):
            v = acc[i] + math.sin(w * i) * inv
            acc[i] = v
            a = -v if v < 0.0 else v
            if a > pk:
                pk = a
        peaks.append(pk)
    # Q30, not Q31: the normaliser is 1/peak and peak <= 1, so the value is
    # >= 1.0 and CANNOT fit in a signed Q31 (1/0.92603 = 1.0799 -> 2.32e9,
    # past INT32_MAX; C++ rejects the literal as a narrowing conversion).
    # Q30 leaves headroom to 2.0. The shift is emitted as a macro rather than
    # hard-coded in the consumer, because a table scale and a consumer shift
    # that disagree produce a square 2 dB off in silence.
    gibbs = [int(round((1.0 / pk) * 2**GIBBS_SHIFT)) for pk in peaks]
    assert max(gibbs) <= 2**31 - 1, "Gibbs table exceeds int32"
    assert min(gibbs) >= 2**30, "Gibbs normaliser should never be below 1.0"
    out.append("#define CSD_GEN_GIBBS_SHIFT %d\n\n" % GIBBS_SHIFT)
    emit_table(out, "csd_gen_gibbs_q30", "CSD_GEN_SQ_HARMONICS + 1",
               [0] + gibbs,
               "/* 1/peak(N) in Q%d for a square built from N odd harmonics\n"
               " * (index N; index 0 is unused padding). N=1 is a pure sine,\n"
               " * peak 1.0, so the entry is exactly 2^%d. Indexing by the\n"
               " * terms that actually fit under Nyquist is what keeps the\n"
               " * delivered peak at the requested amplitude; scale is\n"
               " * CSD_GEN_GIBBS_SHIFT, never a literal in the consumer. */\n"
               % (GIBBS_SHIFT, GIBBS_SHIFT))

    out.append("#endif /* __csd_gen_tables_h__ */\n")

    with open(path, "w") as f:
        f.write("".join(out))

    # Self-checks: a wrong table must fail HERE, never on the target.
    assert abs(sine[SINE_N // 4] - FULL) <= 1, "sine peak wrong"
    assert abs(sine[SINE_N // 2]) <= 2, "sine zero crossing wrong"
    assert abs(sine[3 * SINE_N // 4] + FULL) <= 1, "sine trough wrong"
    assert abs(sine[0]) <= 1 and sine[1] > 0, "sine start wrong"

    # Endpoints are exact by construction, and if they are not, every log
    # sweep endpoint is off: exp2(0) must be exactly 1.0 and log2(1) exactly 0.
    assert exp_tab[0] == Q29, "2^0 must be exactly 1.0 in Q29"
    assert exp_tab[EXP_N] == 2 * Q29, "2^1 must be exactly 2.0 in Q29"
    assert log_tab[0] == 0, "log2(1) must be exactly 0"
    assert log_tab[EXP_N] == Q29, "log2(2) must be exactly 1.0 in Q29"

    # Round trip through the two tables using the STORED INTEGERS and the
    # same decomposition the firmware uses. Two earlier versions of this check
    # were worthless: one reduced to `2**y - 2**y == 0`, and the other masked
    # with `% EXP_N`, reproducing inside the checker the very wrap-around bug
    # that made a 4093 Hz tone come out at 2654 Hz. A check that shares the
    # implementation's mistake certifies the mistake.
    def firmware_exp2(x_q24):
        if x_q24 <= 0:
            return 256                                  # 1.0 Hz in Q8
        ip, frac = x_q24 >> 24, x_q24 & 0xFFFFFF
        i, sub = frac >> 16, frac & 0xFFFF
        mant = exp_tab[i] + (((exp_tab[i + 1] - exp_tab[i]) * sub) >> 16)
        return ((mant << ip) + (1 << 28)) >> 29

    def firmware_log2(v_q8):
        p, t = 0, v_q8
        while t > 1:
            t >>= 1
            p += 1
        if p == 0:
            return 0
        frac = (((v_q8 << (31 - p)) & 0xFFFFFFFF) >> 8) & 0x7FFFFF
        i, sub = frac >> 15, frac & 0x7FFF
        lf = log_tab[i] + (((log_tab[i + 1] - log_tab[i]) * sub) >> 15)
        return (p << 24) + (lf >> 5)

    # Sweep the whole specified range, not samples of it: the failure mode was
    # specific to frequencies whose log2 fraction sits near 1, and a sampled
    # check of round numbers (1, 10, 100, 1000...) passes on exactly those
    # because powers of two have fraction 0.
    worst_rel, worst_abs, worst_f = 0.0, 0.0, 0
    for f_hz in range(1, 24001):
        v = f_hz << 8
        got = firmware_exp2(firmware_log2(v))
        rel = abs(got - v) / v
        if rel > worst_rel:
            worst_rel, worst_f = rel, f_hz
        worst_abs = max(worst_abs, abs(got - v) / 256.0)
    assert worst_rel < 5e-6, \
        "exp2/log2 round trip off by %.2e at %d Hz" % (worst_rel, worst_f)
    # Gibbs table: monotone decreasing toward the Gibbs limit, and every entry
    # must actually bring the peak to <= 1.0 -- that is the whole point.
    assert gibbs[0] in (2**GIBBS_SHIFT, 2**GIBBS_SHIFT - 1), \
        "N=1 must be a pure sine, no scaling"
    for N in range(1, SQ_HARMONICS + 1):
        assert 1.0 / peaks[N - 1] >= 1.0, "peak below 1.0 at N=%d" % N
        assert 1.0 / peaks[N - 1] < 1.10, "implausible overshoot at N=%d" % N
        if N > 1:
            assert peaks[N - 1] <= peaks[N - 2] + 1e-9, "peak not monotone at N"
    print("  gibbs: N=1 %.5f  N=2 %.5f  N=16 %.5f  N=32 %.5f"
          % (peaks[0], peaks[1], peaks[15], peaks[31]))
    print("wrote %s: sine %d, exp2/log2 %d nodes; round trip <= %.1e rel "
          "(%.4f Hz) worst at %d Hz"
          % (path, SINE_N, EXP_N + 1, worst_rel, worst_abs, worst_f))


if __name__ == "__main__":
    sys.exit(main() or 0)
