"""Design the CSD upsampling filters and emit fixed-point C tables.

Two independent stages, both LINEAR PHASE (symmetric FIR):

  Stage A  polyphase sinc interpolator, 48/96/192 kHz -> 384 kHz
           windowed-sinc (Kaiser), cutoff 0.45*fs_in, one prototype per ratio.
           Sinc, not linear interpolation: linear interpolation is a 2-tap
           triangular kernel whose image rejection is ~-13 dB at 48 kHz; this
           design targets >= 80 dB, which only a long sinc can reach.

  Stage B  384 kHz band-limiting / noise-shaping low-pass with a 15 kHz corner.
           Its MAGNITUDE follows a 4th-order Butterworth (monotone, -12 dB/oct
           asymptote), but it is realised as a symmetric FIR so the phase is
           exactly linear and group delay is flat -- a real 4th-order IIR
           Butterworth has frequency-dependent group delay, which is what the
           "minimum group delay dispersion" requirement excludes.

Run:  python3 tools/dsp/gen_upsample_taps.py        (writes src/dsp/csd_dsp_taps.h)
      python3 -m unittest tools.dsp.test_gen_upsample_taps
"""
import cmath
import math

FS_OUT = 384000
RATIOS = {48000: 8, 96000: 4, 192000: 2}

# ---- stage A -----------------------------------------------------------
A_ATTEN_DB = 80.0      # image rejection target
A_PASS_EDGE = 0.45     # cutoff as a fraction of fs_in
A_TAPS_MIN = 64        # per phase minimum

# ---- stage B -----------------------------------------------------------
B_FC = 15000.0         # corner (-3 dB) of the 4th-order equivalent
B_N = 511              # ODD length: symmetry about (N-1)/2 is what makes phase exactly linear


def kaiser_beta(atten_db):
    if atten_db > 50:
        return 0.1102 * (atten_db - 8.7)
    if atten_db > 21:
        return 0.5842 * (atten_db - 21) ** 0.4 + 0.07886 * (atten_db - 21)
    return 0.0


def bessel_i0(x):
    s, t, k = 1.0, 1.0, 1
    while t > 1e-12 * s:
        t *= (x / (2.0 * k)) ** 2
        s += t
        k += 1
    return s


def kaiser_window(n, length, beta):
    d = (length - 1) / 2.0
    denom = bessel_i0(beta)
    return bessel_i0(beta * math.sqrt(max(0.0, 1.0 - ((n - d) / d) ** 2))) / denom


def lowpass_sinc(n_taps, fc_norm):
    """fc_norm = cutoff / sample_rate, 0 < fc_norm < 0.5."""
    d = (n_taps - 1) / 2.0
    return [2 * fc_norm * (1.0 if n == d else math.sin(2 * math.pi * fc_norm * (n - d)) / (2 * math.pi * fc_norm * (n - d)))
            for n in range(n_taps)]


def design_interpolator(fs_in, atten_db=A_ATTEN_DB, taps_min=A_TAPS_MIN):
    """Prototype filter at the OUTPUT rate, cut into `L` polyphase phases."""
    L = RATIOS[fs_in]
    # passband edge as a fraction of fs_in (NOT of Nyquist); the first image sits
    # centred on fs_in, so the stopband has to start by fs_in - f_pass
    f_pass = A_PASS_EDGE * fs_in
    f_stop = fs_in - f_pass          # first image starts here (e.g. 26.4k at 48k)
    df = (f_stop - f_pass) / FS_OUT
    beta = kaiser_beta(atten_db)
    # Kaiser length estimate
    n = int(math.ceil((atten_db - 7.95) / (2.285 * 2 * math.pi * df))) + 1
    n = max(n, taps_min * L)
    n += (-n) % L                     # whole number of phases
    fc = (f_pass + f_stop) / 2.0 / FS_OUT
    proto = [h * kaiser_window(i, n, beta) for i, h in enumerate(lowpass_sinc(n, fc))]
    # Each output sample is built from ONE phase, so every phase must carry the
    # whole DC gain. Normalising the prototype to sum=1 would make DC come out at
    # 1/L (-18 dB at 8x); the prototype therefore sums to L.
    gain = sum(proto) / L
    proto = [h / gain for h in proto]
    return L, proto


def butterworth4_mag(f, fc):
    return 1.0 / math.sqrt(1.0 + (f / fc) ** 8)


def design_bandlimit(fc=B_FC, n=B_N):
    """Linear-phase FIR whose magnitude follows |H4| of a 4th-order Butterworth.

    Zero-phase frequency response sampled on an n-point grid, inverse transformed
    to a symmetric impulse response -> exactly linear phase, flat group delay.
    """
    half = (n - 1) // 2
    h = []
    for i in range(n):
        m = i - half
        acc = 0.0
        for k in range(n):
            f = k * FS_OUT / n
            if f > FS_OUT / 2:
                f = FS_OUT - f                    # mirror
            acc += butterworth4_mag(f, fc) * math.cos(2 * math.pi * k * m / n)
        h.append(acc / n)
    h = [x * kaiser_window(i, n, kaiser_beta(90.0)) for i, x in enumerate(h)]
    gain = sum(h)
    return [x / gain for x in h]


def to_q30(values):
    q = []
    for v in values:
        s = int(round(v * (1 << 30)))
        q.append(max(-(1 << 31), min((1 << 31) - 1, s)))
    return q


def emit(path=None):
    if path is None:
        import os
        path = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..", "src", "dsp", "csd_dsp_taps.h")
    lines = ["/* Generated by tools/dsp/gen_upsample_taps.py -- do not edit by hand.",
             " * Q30 signed coefficients, linear-phase FIR, unity DC gain. */",
             "#ifndef CSD_DSP_TAPS_H", "#define CSD_DSP_TAPS_H", "",
             "#include <stdint.h>", "",
             f"#define CSD_DSP_FS_OUT {FS_OUT}u", ""]
    for fs_in, L in RATIOS.items():
        Ld, proto = design_interpolator(fs_in)
        q = to_q30(proto)
        n = len(q)
        tpp = n // L
        lines.append(f"/* {fs_in} Hz -> {FS_OUT} Hz: L={Ld}, {n} taps, {tpp} per phase */")
        lines.append(f"#define CSD_UP{fs_in // 1000}_PHASES {Ld}u")
        lines.append(f"#define CSD_UP{fs_in // 1000}_TAPS_PER_PHASE {tpp}u")
        lines.append(f"static const int32_t csd_up{fs_in // 1000}_coef[{n}] = {{")
        for i in range(0, n, 8):
            lines.append("    " + ", ".join(str(v) for v in q[i:i + 8]) + ",")
        lines.append("};")
        lines.append("")
    hb = to_q30(design_bandlimit())
    lines.append(f"/* 384 kHz band-limit: 4th-order Butterworth magnitude, fc={B_FC:.0f} Hz, linear phase */")
    lines.append(f"#define CSD_BL_TAPS {len(hb)}u")
    lines.append(f"#define CSD_BL_DELAY {(len(hb) - 1) // 2}u")
    lines.append(f"static const int32_t csd_bl_coef[{len(hb)}] = {{")
    for i in range(0, len(hb), 8):
        lines.append("    " + ", ".join(str(v) for v in hb[i:i + 8]) + ",")
    lines.append("};")
    lines.append("")
    lines.append("#endif /* CSD_DSP_TAPS_H */")
    with open(path, "w") as f:
        f.write("\n".join(lines) + "\n")
    return path


if __name__ == "__main__":
    print("wrote", emit())
