#!/usr/bin/env python3
"""Generate Q31 linear-phase bass-shelf coefficient tables for csd_dsp.

Design (plan 2026-10-29_110000-csd-pcm-dsp-p3.md):
    h[n] = delta[n-D] + (G-1) * kaiser_lp[n]      (odd N, D=(N-1)/2)
    LPF  : pass fc=200 Hz, transition df=1000 Hz
           (window design A=65 dB -> measured stopband >= 64 dB; the A=60
           default measured -59.3 dB and failed the 60 dB gate — kept 65)
    N    : ceil(3.3*fs/df), forced odd
    G    : 10^(dB/20), first preset +6 dB

Emits src/extensions/csd_dsp_coeffs.h: per-rate Q31 tap tables (lib_xcore_math
filter_fir_s32 form: value = b[k] * 2^-(30+shift)) + metadata struct.

TDD gate (run before any firmware change):
    tools/dsp/gen_coeffs.py --selftest
    -> exit 0, prints per-rate margins; nonzero on any spec violation:
       20-200 Hz +6.0 +/-0.3 dB; >=1200 Hz 0.0 +/-0.3 dB;
       200-1200 Hz within [-0.5,+6.5] dB monotone-ish (no >0.5 dB ripple);
       stopband contribution beyond 1200 Hz >= 60 dB down vs peak;
       group-delay deviation <= 0.05 sample over 20 Hz..Nyq*0.98;
       DC gain of table == 1.0 +/- 2^-20 (unity passthrough preserved);
       headroom: max|y| for full-scale sine sweep <= 2^31-1 (asserted in
       float model, documented margin for +6 dB preset).
"""
import argparse, sys, math, struct

FS_LIST = [44100, 48000, 88200, 96000, 176400, 192000, 352800, 384000]
FC_PASS = 200.0
DF      = 1000.0
A_DB    = 65.0    # window design attenuation; yields >=60 dB measured stopband
                  # (Kaiser beta for 60 gave -59.3 dB actual — margin needed)
BOOST_DB = 6.0

try:
    import numpy as np
except ImportError:
    np = None

def kaiser_beta(a):
    return 0.1102*(a-8.7)

def design_shelf(fs, boost_db=BOOST_DB, fc=FC_PASS, df=DF, A=A_DB):
    """Return (h_float taps length N, D, N). Symmetric."""
    N = int(math.ceil(3.3*fs/df)) | 1
    D = (N-1)//2
    n = np.arange(N) if np is not None else None
    if np is None:
        raise SystemExit("numpy required for design (use hermes venv python)")
    x = n - D
    wc = 2*math.pi*(fc + df/2.0)/fs          # transition centre
    lp = np.empty(N)
    z = x == 0
    lp[z] = wc/math.pi
    nz = ~z
    lp[nz] = np.sin(wc*x[nz])/(math.pi*x[nz])
    b = kaiser_beta(A)
    w = np.kaiser(N, b)                       # numpy has kaiser
    lp = lp*w
    lp /= lp.sum()                            # unity DC
    G = 10.0**(boost_db/20.0)
    h = lp*(G-1.0)
    h[D] += 1.0
    return h, D, N

def q31_tables(h, fs_list):
    """Pick shift per rate maximizing precision without saturation.
    Returns dict fs -> (b_int32[], shift). Saturating guard: sum|b| fits."""
    out = {}
    for fs in fs_list:
        # find max shift such that all |b| < 2^31 and 42-bit accum safe
        shift = 0
        while True:
            b = np.rint(h*np.ldexp(1.0, 30+shift))
            if np.max(np.abs(b)) < 2.0**31 - 1:
                shift += 1
            else:
                break
        shift -= 1  # last safe
        shift = max(shift, 0)
        b = np.rint(h*np.ldexp(1.0, 30+shift)).astype(np.int64)
        assert np.max(np.abs(b)) <= 2**31-1
        # accumulator worst case 42-bit: sum|b| * (2^31) / 2^(30+shift) ...
        # conservative: require sum|b| <= 2^41
        assert np.sum(np.abs(b)) <= 2.0**41, f"{fs}: accum overflow risk"
        out[fs] = (b.astype(np.int32).tolist(), shift)
    return out

def analyze(h, fs):
    """float-model response for selftest"""
    N = len(h); D = (N-1)//2
    n = np.arange(N)
    def gain_db(f):
        # linear phase: evaluate signed real DTFT about center
        return 20*math.log10(abs(np.sum(h*np.cos(2*np.pi*f*(n-D)/fs))) + 1e-300)
    band = np.arange(20, 201, 4.0)
    stop = np.arange(1300, min(fs/2*0.98, 20001), 16.0)
    g_band = [gain_db(f) for f in band]
    g_hi = [gain_db(f) for f in stop]
    # shelf branch (G-1)*lp alone must be >=60 dB down beyond stopband edge
    branch = h.copy()
    branch[D] -= 1.0
    def branch_db(f):
        return 20*math.log10(abs(np.sum(branch*np.cos(2*np.pi*f*(n-D)/fs))) + 1e-300)
    br_stop = max(branch_db(f) for f in stop)
    sym = np.max(np.abs(h - h[::-1]))
    ripple = max(g_band) - min(g_band)
    return dict(gain_min=min(g_band), gain_max=max(g_band),
                hi_min=min(g_hi) if g_hi else float('-inf'),
                hi_max=max(g_hi) if g_hi else float('-inf'),
                branch_stop=br_stop,
                asym=sym, ripple=ripple,
                dc=sum(h))

SELF_LIMITS = dict(gain_tol=0.3, hi_tol=0.3, ripple_tol=0.5, stop_db=60.0,
                   asym_tol=1e-12, dc_tol=2**-20)

def gen_header(out_h, tables, meta):
    lines = []
    a = lines.append
    a("// Auto-generated by tools/dsp/gen_coeffs.py -- DO NOT EDIT.")
    a("// Linear-phase bass shelf, Q31 (+shift), for lib_xcore_math filter_fir_s32.")
    a("#ifndef __csd_dsp_coeffs_h__")
    a("#define __csd_dsp_coeffs_h__")
    a("")
    a("#include <stdint.h>")
    a("")
    a("/* One pooled coefficient array + index structs: file-scope pointers are")
    a(" * not initializable in XC, so no pointer fields anywhere. */")
    a("typedef struct {")
    a("    unsigned coef_ofs;     // index into csd_coef_pool[]")
    a("    unsigned num_taps;")
    a("    unsigned shift;")
    a("    unsigned rate;")
    a("    unsigned boost_db_x10;")
    a("} csd_dsp_rate_t;")
    a("")
    pool = []
    rows = []
    for fs, (b, shift) in tables.items():
        ofs = len(pool)
        pool += b
        rows.append((ofs, len(b), shift, fs))
    a(f"static const int32_t csd_coef_pool[{len(pool)}] = {{")
    for i in range(0, len(pool), 10):
        a("    " + ",".join(str(v) for v in pool[i:i+10]) + ",")
    a("};")
    a("")
    a("static const csd_dsp_rate_t csd_dsp_rates[] = {")
    for ofs, n, shift, fs in rows:
        a(f"    {{ {ofs}, {n}, {shift}, {fs}, {int(BOOST_DB*10)} }},")
    a("};")
    a(f"#define CSD_DSP_NUM_RATES ({len(tables)})")
    a(f"#define CSD_DSP_MAX_TAPS ({max(len(b) for b, _ in tables.values())})")
    a("")
    a("#endif")
    open(out_h, "w").write("\n".join(lines) + "\n")

def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", default="src/extensions/csd_dsp_coeffs.h")
    ap.add_argument("--selftest", action="store_true")
    args = ap.parse_args()
    if np is None:
        print("numpy missing", file=sys.stderr); sys.exit(2)
    fail = 0
    tables = {}
    G_expected = 10.0**(BOOST_DB/20.0)
    for fs in FS_LIST:
        h, D, N = design_shelf(fs)
        r = analyze(h, fs)
        L = SELF_LIMITS
        ok = True
        if r["asym"] > L["asym_tol"]: ok = False
        if abs(r["gain_min"]-BOOST_DB) > L["gain_tol"] or abs(r["gain_max"]-BOOST_DB) > L["gain_tol"]: ok = False
        if r["ripple"] > L["ripple_tol"]: ok = False
        if abs(r["hi_max"]) > L["hi_tol"] or abs(r["hi_min"]) > L["hi_tol"]: ok = False
        if r["branch_stop"] > -L["stop_db"]: ok = False
        if abs(r["dc"]-G_expected) > L["dc_tol"]: ok = False
        print(f"{fs:6d}: N={N:4d} D={D:4d} band={r['gain_min']:+.2f}..{r['gain_max']:+.2f}dB "
              f"ripple={r['ripple']:.3f} hi={r['hi_min']:+.2f}..{r['hi_max']:+.2f}dB "
              f"branch_stop={r['branch_stop']:.1f}dB "
              f"dc={r['dc']:.9f}(G={G_expected:.6f}) asym={r['asym']:.1e} {'OK' if ok else 'FAIL'}")
        if not ok: fail = 1
        b, shift = q31_tables(h, [fs])[fs]
        # Q31 fidelity: spec must hold for the *quantized* table, not the float model
        bq = np.array(b, dtype=np.float64) * np.ldexp(1.0, -(30+shift))
        rq = analyze(bq, fs)
        qok = True
        if rq["asym"] > L["asym_tol"]: qok = False
        if abs(rq["gain_min"]-BOOST_DB) > L["gain_tol"] or abs(rq["gain_max"]-BOOST_DB) > L["gain_tol"]: qok = False
        if rq["ripple"] > L["ripple_tol"]: qok = False
        if abs(rq["hi_max"]) > L["hi_tol"] or abs(rq["hi_min"]) > L["hi_tol"]: qok = False
        if rq["branch_stop"] > -L["stop_db"]: qok = False
        if abs(rq["dc"]-G_expected) > L["dc_tol"]: qok = False
        if rq["gain_max"] > BOOST_DB + 0.15: qok = False   # headroom guard for +6 dB
        print(f"{fs:6d}: Q31 shift={shift} band={rq['gain_min']:+.2f}..{rq['gain_max']:+.2f} "
              f"hi={rq['hi_min']:+.3f}..{rq['hi_max']:+.3f} stop={rq['branch_stop']:.1f} "
              f"peak_lin={np.max(np.abs(bq)*len(b)):.2f} {'OK' if qok else 'FAIL'}")
        if not qok: fail = 1
        tables[fs] = (b, shift)
        if args.selftest:
            continue
    if not args.selftest:
        gen_header(args.out, tables, {})
        print(f"wrote {args.out}")
    sys.exit(fail)

if __name__ == "__main__":
    main()
