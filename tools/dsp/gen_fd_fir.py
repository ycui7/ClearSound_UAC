#!/usr/bin/env python3
"""Generate XMOS's own frequency-domain block-FIR kernels for the CSD shelf.

Kernel + coefficient maths are lib_audio_dsp's (AN02027,
examples/app_fd_block_fir). Taps come from gen_coeffs.design_shelf -- the same
design gen_coeffs --selftest gates. This script only:
  1. drives the vendor generator once per rate,
  2. const-qualifies the emitted coefficient arrays (read-only at runtime, so
     they belong in flash: 8 rate tables would otherwise eat ~40 KiB of RAM),
  3. emits src/extensions/csd_dsp_fd_conf.h -- the rate-indexed table the
     firmware engine (csd_dsp_fd.c) selects from.

Run with the generator venv:
  tools/dsp/.venv-dspgen/bin/python tools/dsp/gen_fd_fir.py
"""
import os, re, sys
import numpy as np

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import gen_coeffs as g

from audio_dsp.dsp.fd_block_fir import fir_block_fd

RATES = g.FS_LIST
FRAME_ADVANCE = int(os.environ.get("CSD_FRAME_ADVANCE", "128"))
OUT_DIR = os.path.abspath(os.path.join(HERE, "..", "..", "src", "extensions"))


def _expr_of(src, name):
    """The vendor's DATA_BUFFER_ELEMENTS expression, verbatim. Sized by the C
    compiler (it contains sizeof(bfp_complex_s32_t)) -- never evaluate it here,
    or a wrong sizeof silently under-allocates the kernel state."""
    m = re.search(rf"#define {name}_DATA_BUFFER_ELEMENTS \((.*?)\)\n", src, re.S)
    if not m:
        raise RuntimeError(f"{name}: missing DATA_BUFFER_ELEMENTS")
    return m.group(1).strip()


def make_rate(fs):
    """One rate: vendor generator, then const-qualify the read-only tables."""
    h, D, N = g.design_shelf(fs)
    if os.environ.get("CSD_TEST_DELTA"):
        # DIAGNOSTIC ONLY (device-execution proof): δ at center of the same
        # tap count/geometry -> unity through the whole block path. Never ship.
        h = np.zeros(N); h[N // 2] = 1.0
    notch = os.environ.get("CSD_TEST_NOTCH_HZ")
    if notch:
        # DIAGNOSTIC ONLY (device-execution proof): full-length notch at f,
        # unity elsewhere. Never ship with this set.
        from scipy.signal import firwin
        f = float(notch); bw = 50.0
        if not (bw < f < fs / 2 - bw):
            raise RuntimeError(f"notch {f}Hz invalid for fs={fs}")
        bp = firwin(N, [f - bw, f + bw], pass_zero=False, fs=fs)
        h = np.zeros(N); h[N // 2] = 1.0; h -= bp
    name = f"csdfd_{fs}"
    coef_path = os.path.join(HERE, f"{name}.npy")
    np.savetxt(coef_path, h, fmt="%.12e")
    for p in (os.path.join(OUT_DIR, f"{name}.h"),
              os.path.join(OUT_DIR, f"{name}_debug.h")):
        if os.path.exists(p):
            os.remove(p)
    fir_block_fd(fs=float(fs), n_chans=2, coeffs_path=coef_path,
                 filter_name=name, output_path=OUT_DIR,
                 frame_advance=FRAME_ADVANCE)

    path = os.path.join(OUT_DIR, f"{name}.h")
    src = open(path).read()

    def want(pat, what):
        m = re.search(pat, src)
        if not m:
            raise RuntimeError(f"{fs}: generated header missing {what}")
        return m.group(1)

    meta = dict(
        name=name,
        tdl=int(want(rf"#define {name}_TD_BLOCK_LENGTH \((\d+)\)", "TD_BLOCK_LENGTH")),
        blocks=int(want(rf"#define {name}_BLOCK_COUNT \((\d+)\)", "BLOCK_COUNT")),
        fa=int(want(rf"#define {name}_FRAME_ADVANCE \((\d+)\)", "FRAME_ADVANCE")),
        fo=int(want(rf"#define {name}_FRAME_OVERLAP \((\d+)\)", "FRAME_OVERLAP")),
        tpb=int(want(r"taps_per_block = (\d+)", "taps_per_block")),
        buf_expr=_expr_of(src, name),
        num_taps=N, rate=fs,
    )
    # Vendor default kept: coefficient tables stay mutable RAM. Const-qualifying
    # them (to save ~40 KiB in flash) coincided with tile[1] dying at stream
    # start -- all rates silent including DoP. 40 KiB of 512 KiB tile RAM is not
    # worth an unproven deviation from the vendor kernel's usage.
    open(path, "w").write(src)
    return meta


def emit_conf(metas):
    fas = {m["fa"] for m in metas}
    if len(fas) != 1:
        raise RuntimeError(f"mixed frame advance {fas}")
    L = []
    a = L.append
    a("// Auto-generated by tools/dsp/gen_fd_fir.py -- DO NOT EDIT.")
    a("#ifndef __csd_dsp_fd_conf_h__")
    a("#define __csd_dsp_fd_conf_h__")
    a("")
    a('#include "dsp/fd_block_fir.h"')
    for m in metas:
        a(f'#include "{m["name"]}.h"')
    a("")
    a(f"#define CSD_FD_FRAME_ADVANCE ({fas.pop()})")
    a(f"#define CSD_FD_NUM_RATES ({len(metas)})")
    a("")
    a("/* Kernel-state sizing is done by the C compiler from the vendor's own")
    a(" * DATA_BUFFER_ELEMENTS macros (they contain sizeof(bfp_complex_s32_t));")
    a(" * evaluating them in Python would risk under-allocation. */")
    a("#define CSD_FD_MAX2(a, b) ((a) > (b) ? (a) : (b))")
    a("#define CSD_FD_MAX4(a, b, c, d) CSD_FD_MAX2(CSD_FD_MAX2(a, b), CSD_FD_MAX2(c, d))")
    a("#define CSD_FD_MAX8(a,b,c,d,e,f,g,h) \\")
    a("        CSD_FD_MAX2(CSD_FD_MAX4(a,b,c,d), CSD_FD_MAX4(e,f,g,h))")
    a("#define CSD_FD_MAX_DATA_WORDS                                       \\")
    a("    CSD_FD_MAX8(" + ", ".join(f"{m['name']}_DATA_BUFFER_ELEMENTS"
                                     for m in metas) + ")")
    a("#define CSD_FD_MAX_TD_BLOCK_LENGTH                                  \\")
    a("    CSD_FD_MAX8(" + ", ".join(f"{m['name']}_TD_BLOCK_LENGTH"
                                     for m in metas) + ")")
    a("")
    a("/* Rate-indexed selection for csd_dsp_fd.c. coef_blocks live in flash")
    a(" * (const-qualified by the generator). */")
    a("typedef struct {")
    a("    const bfp_complex_s32_t *coef_blocks;")
    a("    unsigned td_block_length;")
    a("    unsigned block_count;")
    a("    unsigned taps_per_block;")
    a("    unsigned frame_advance;")
    a("    unsigned frame_overlap;")
    a("    unsigned data_words;")
    a("    unsigned num_taps;")
    a("    unsigned rate;")
    a("} csd_dsp_fd_rate_t;")
    a("")
    a("static const csd_dsp_fd_rate_t csd_dsp_fd_rates[] = {")
    for m in metas:
        a(f"    {{ coef_blocks_{m['name']}, {m['name']}_TD_BLOCK_LENGTH, "
          f"{m['name']}_BLOCK_COUNT, {m['tpb']}, {m['name']}_FRAME_ADVANCE, "
          f"{m['name']}_FRAME_OVERLAP, {m['name']}_DATA_BUFFER_ELEMENTS, "
          f"{m['num_taps']}, {m['rate']} }},")
    a("};")
    a("")
    a("#endif")
    open(os.path.join(OUT_DIR, "csd_dsp_fd_conf.h"), "w").write("\n".join(L) + "\n")


def main():
    os.makedirs(OUT_DIR, exist_ok=True)
    metas = []
    for fs in RATES:
        m = make_rate(fs)
        metas.append(m)
        print(f"fs={fs:6d} taps={m['num_taps']:4d} td_block={m['tdl']} "
              f"blocks={m['blocks']} tpb={m['tpb']} fa={m['fa']} fo={m['fo']}")
    emit_conf(metas)
    print(f"wrote csd_dsp_fd_conf.h + {len(metas)} rate headers in {OUT_DIR}")


if __name__ == "__main__":
    main()
