#!/usr/bin/env bash
# Emit the firmware build version as a header the firmware can compile in.
#
#   version = [year].[month].[day].[count]-[commit]   e.g. 2026.10.30.3-a13c2c2-dirty
#
# Date is UTC so a build near midnight cannot land on two dates in one
# session. commit is the short HEAD hash of THIS repo, with -dirty appended
# when the working tree differs from HEAD, because a build made from a dirty
# tree is not reproducible from the hash alone and must say so.
#
# count restarts at 1 each day. It is a build number, not a timestamp: its
# only job is to distinguish two builds cut on the same date, so the one
# loaded on the bench can be named unambiguously.
#
# Only a real compile should burn a count, so this runs at cmake configure
# time -- our build entry configures on every build.
#
# Usage: tools/gen_version.sh [repo-root] [output-header]
set -u

REPO="${1:-$(cd "$(dirname "$0")/.." && pwd)}"
OUT="${2:-$REPO/src/extensions/csd_version.h}"

if ! cd "$REPO" 2>/dev/null; then
    echo "gen_version: not a directory: $REPO" >&2
    exit 1
fi

COMMIT=$(git rev-parse --short=7 HEAD 2>/dev/null)
if [ -z "$COMMIT" ]; then
    # No git at all (source tree handed over as an archive). Say so rather
    # than invent a hash that would look like a real commit.
    COMMIT="nogit"
else
    # Untracked files count as dirty: a new .c under src/ is compiled into
    # the image by the include glob, so a build containing one is not
    # reproducible from HEAD's hash either. Generated and build outputs are
    # gitignore'd, so they do not trip this.
    if [ -n "$(git status --porcelain --untracked-files=all 2>/dev/null)" ]; then
        COMMIT="$COMMIT-dirty"
    fi
fi

read -r Y M D < <(date -u '+%Y %m %d')
DAY="$Y.$M.$D"

STATE="$REPO/.build_count"
STORED_DAY=""
COUNT=0
if [ -f "$STATE" ]; then
    read -r STORED_DAY COUNT < "$STATE" || true
fi
if [ "$STORED_DAY" != "$DAY" ]; then
    COUNT=0
fi
COUNT=$((COUNT + 1))
printf '%s %s\n' "$DAY" "$COUNT" > "$STATE"

VERSION="$DAY.$COUNT-$COMMIT"

# Only rewrite when it changed: a header touched on every configure would
# rebuild every file that includes it.
NEW=$(mktemp)
{
    echo "/* Generated by tools/gen_version.sh -- do not edit by hand."
    echo " * Rebuilt on every cmake configure; .build_count holds the day's count. */"
    echo "#ifndef CSD_VERSION_H"
    echo "#define CSD_VERSION_H"
    echo ""
    echo "#define CSD_FW_VERSION \"$VERSION\""
    echo "#define CSD_FW_COMMIT  \"${COMMIT}\""
    echo ""
    echo "#endif /* CSD_VERSION_H */"
} > "$NEW"

if [ -f "$OUT" ] && cmp -s "$NEW" "$OUT"; then
    rm -f "$NEW"
else
    mv "$NEW" "$OUT"
    echo "csd_version.h -> $VERSION"
fi

echo "$VERSION"
